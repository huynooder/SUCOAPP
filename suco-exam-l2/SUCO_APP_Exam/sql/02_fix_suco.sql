CREATE TABLE SUCO (
    MaSC            VARCHAR2(10),
    TieuDe          NVARCHAR2(200)  NOT NULL,
    MoTa            NVARCHAR2(2000),
    MaDM            NUMBER          NOT NULL,
    MucDo           VARCHAR2(20)    NOT NULL,
    TrangThai       VARCHAR2(20)    DEFAULT 'MOI' NOT NULL,
    MaNguoiBaoCao   NUMBER          NOT NULL,
    MaNguoiXuLy     NUMBER,
    NgayTao         TIMESTAMP       DEFAULT SYSTIMESTAMP,
    NgayCapNhat     TIMESTAMP,
    NguyenNhan      NVARCHAR2(1000),
    CachKhacPhuc    NVARCHAR2(1000),
    CONSTRAINT PK_SUCO PRIMARY KEY (MaSC),
    CONSTRAINT FK_SUCO_DANHMUC FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM),
    CONSTRAINT FK_SUCO_BAOCAO FOREIGN KEY (MaNguoiBaoCao) REFERENCES NGUOIDUNG(MaND),
    CONSTRAINT FK_SUCO_XULY FOREIGN KEY (MaNguoiXuLy) REFERENCES NGUOIDUNG(MaND),
    CONSTRAINT CK_SUCO_MUCDO CHECK (MucDo IN ('THAP', 'TRUNG_BINH', 'CAO', 'KHAN_CAP')),
    CONSTRAINT CK_SUCO_TRANGTHAI CHECK (TrangThai IN ('MOI', 'DANG_XU_LY', 'DA_XU_LY', 'DONG'))
);

-- Sequence sinh ma SC0001, SC0002...
CREATE SEQUENCE SEQ_SUCO START WITH 1 INCREMENT BY 1 NOCACHE;

-- Trigger tu dong gan MaSC + NgayCapNhat
CREATE OR REPLACE TRIGGER TRG_SUCO_MA
BEFORE INSERT ON SUCO
FOR EACH ROW
BEGIN
    IF :NEW.MaSC IS NULL THEN
        :NEW.MaSC := 'SC' || LPAD(SEQ_SUCO.NEXTVAL, 4, '0');
    END IF;
    :NEW.NgayCapNhat := SYSTIMESTAMP;
END;
/

-- Bang lich su
CREATE TABLE LICHSU_XULY (
    MaLS            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaSC            VARCHAR2(10)    NOT NULL,
    MaNguoiThucHien NUMBER          NOT NULL,
    TrangThaiCu     VARCHAR2(20),
    TrangThaiMoi    VARCHAR2(20)    NOT NULL,
    GhiChu          NVARCHAR2(1000),
    NguyenNhan      NVARCHAR2(1000),
    CachKhacPhuc    NVARCHAR2(1000),
    ThoiGian        TIMESTAMP       DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_LS_SUCO FOREIGN KEY (MaSC) REFERENCES SUCO(MaSC),
    CONSTRAINT FK_LS_NGUOI FOREIGN KEY (MaNguoiThucHien) REFERENCES NGUOIDUNG(MaND)
);

-- View thong ke (neu chua co)
CREATE OR REPLACE VIEW V_THONGKE_TRANGTHAI AS
SELECT TrangThai, COUNT(*) AS SoLuong
FROM SUCO
GROUP BY TrangThai;

CREATE OR REPLACE VIEW V_THONGKE_DANHMUC AS
SELECT d.TenDM, COUNT(s.MaSC) AS SoLuong
FROM DANHMUC d
LEFT JOIN SUCO s ON d.MaDM = s.MaDM
GROUP BY d.TenDM;

CREATE OR REPLACE VIEW V_THONGKE_THANG AS
SELECT TO_CHAR(NgayTao, 'YYYY-MM') AS Thang, COUNT(*) AS SoLuong
FROM SUCO
GROUP BY TO_CHAR(NgayTao, 'YYYY-MM')
ORDER BY Thang;

